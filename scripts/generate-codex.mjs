import { spawnSync } from "node:child_process";
import { writeFileSync, mkdirSync, rmSync } from "node:fs";
const binary = process.env.CODEX_BIN || "node_modules/.bin/codex";
const version = spawnSync(binary, ["--version"], { encoding: "utf8" });
if (version.status !== 0) throw new Error("Cannot resolve Codex version");
mkdirSync("generated", { recursive: true });
rmSync("generated/codex", { recursive: true, force: true });
const result = spawnSync(
  binary,
  ["app-server", "generate-ts", "--experimental", "--out", "generated/codex"],
  { stdio: "inherit" },
);
if (result.status !== 0) process.exit(1);
writeFileSync(
  "generated/version.ts",
  `// Generated by scripts/generate-codex.mjs\nexport const CODEX_VERSION = ${JSON.stringify(version.stdout.trim())};\n`,
);
